"use server";

import { revalidatePath } from "next/cache";

import type { NotificationBellItem } from "@dss/ui";

import { getSessionUser } from "@/lib/auth/session";
import { dismissPortalNotifications } from "@/lib/auth/oidc";
import { vetDismissKeys } from "@/lib/domain/notifications";

/**
 * ============================================================================
 * 알림 지움 — 서버 액션 (「이 알림은 그만 보겠다」)
 * ============================================================================
 * 종의 줄에서 ✕ 를 누르면 그 줄을 **포털에** 지운다. 그러면 어느 사내 시스템의
 * 종에서도 사라진다 — 「확인했다」는 그 알림을 만든 시스템에만 적을 수 있지만
 * (바로 옆 notification-acknowledgements.ts), 「그만 보겠다」는 포털 한 곳에
 * 적힌다(2026-10-19 결정, dss-auth/docs/사이트-알림-통로.md).
 *
 * ── 🔴 왜 서버 액션인가 (브라우저용 중계 통로가 아니라) ─────────────────
 * 포털에 지움을 적는 자격은 `client_secret` 이다. 브라우저에서 부를 수 있는
 * 통로(route handler)를 뚫으면 거기서 세션을 다시 검증하고 시크릿을 다시
 * 다뤄야 한다 — **시크릿을 다루는 자리를 하나 더 만드는** 일이다. 그 판단은
 * components/PortalNotificationBell.tsx 머리말에 이미 적혀 있고 여기서 깨지
 * 않는다. 서버 액션이면 시크릿은 이 프로세스 밖으로 나가지 않고, 번들로는
 * **이 함수의 이름표**만 나간다(본문은 서버에 남는다).
 *
 * ── 🔴 누구의 지움인지는 **서버가** 정한다 ──────────────────────────────
 * 사람 번호(`sub`)를 인자로 받지 않는다. 받으면 브라우저가 아무 번호나 실어
 * 남의 알림을 지울 수 있다. 여기서 제 세션을 다시 읽어 그 값을 쓴다 —
 * 레이아웃이 이미 requireSession 을 했더라도 **서버 액션은 따로 다시
 * 검증한다**((app)/layout.tsx 머리말의 약속이 그것이다).
 *
 * 🔴 `redirect` 하는 `requireSession` 이 아니라 `getSessionUser` 를 쓴다. 이
 *    함수는 사람이 ✕ 를 누른 **그 순간** 불리는데, 세션이 막 끊긴 경우에 종
 *    하나 때문에 보던 화면이 로그인으로 튀어서는 안 된다. 그때는 아무 일도
 *    일어나지 않는 편이 맞다.
 *
 * ── 🔴 권한을 따로 보지 않는다 ─────────────────────────────────────────
 * 확인(acknowledge)은 「알림을 받는 사람인가」를 본다 — 우리 DB 의 확인 기록
 * 표에 줄이 쌓이기 때문이다. 지움은 **포털이 그 사람 몫으로만** 적고(sub 는 위
 * 에서 서버가 정했다), 열쇠 모양이 틀리거나 모르는 시스템의 것은 포털이
 * 조용히 버린다. 즉 여기서 할 수 있는 최악이 「제 종에서 제 알림을 지우는 것」
 * 이라, 역할로 한 번 더 가르면 막는 것 없이 「되는 사람과 안 되는 사람」만
 * 생긴다.
 *
 * ── 🔴 던지지 않는다 ───────────────────────────────────────────────────
 * @dss/ui 의 곁들이 조각이 이 함수를 누름 처리 **한가운데서** 부른다
 * (BellBehavior 의 notifyDismissed). 못 지우면 그 줄이 종에 남을 뿐이다.
 *
 * ── 🔵 「확인하는 동안 미리 감추기」와 **다른 것**이다 ──────────────────
 * 클라이언트 껍데기에 hide/restore 가 있는데(NotificationBellWithAcknowledge),
 * 그것은 **확인을 저장하는 동안** 그 줄을 미리 감추는 장치이지 지움이 아니다.
 * 같은 누름에서 둘이 함께 돌지 않는다 — ✕ 단추는 줄의 링크 **밖**(형제)이라
 * 확인 쪽이 찾는 `a.dss-bell__link` 에 걸리지 않는다(@dss/ui 의 BellBehavior).
 * 그래서 여기서는 감추지 않는다. 줄은 아래 revalidate 뒤 **다음 렌더**에서
 * 빠진다.
 * ============================================================================
 */
export async function dismissNotificationAction(item: NotificationBellItem): Promise<void> {
  try {
    const actor = await getSessionUser();
    if (!actor) return;

    // 🔴 열쇠는 브라우저를 거쳐 온 글자다. 모양이 틀리거나 모르는 시스템의
    //    열쇠는 포털이 **조용히 버리므로** 여기서 더 가릴 것은 없지만, 빈 값은
    //    아예 보내지 않는다(그 묶음은 포털이 400 으로 거절한다).
    //    🔵 이 값으로 지워지는 것은 **그 사람 자신의 알림뿐이다** — 누구의
    //    지움인지는 바로 위에서 서버가 정했다.
    const dismissalKey = typeof item?.key === "string" ? item.key : "";
    if (dismissalKey === "") return;

    const recorded = await dismissPortalNotifications(actor.authSub, [dismissalKey]);

    // 🔴 적히지 않았으면 다시 그리지 않는다. 포털이 거절했으면 다음 렌더의
    //    목록도 똑같고, 그때 하는 일이라고는 캐시를 쓸데없이 버리는 것뿐이다.
    //    그 줄은 종에 남는다 — 알고 받아들인 모습이다.
    if (!recorded) return;

    // ── 🔴 왜 `revalidatePath("/", "layout")` 인가 ────────────────────────
    // 종은 **사내 구간 레이아웃**이 그린다((app)/layout.tsx). 라우트 그룹이라
    // URL 에 나타나지 않으므로 경로는 `/` 다. 지금 보고 있는 화면이 무엇이든 그
    // 레이아웃이 다시 그려져야 목록이 줄어든다 — 화면 하나만 되살리면 레이아웃은
    // 그대로라 ✕ 를 눌러도 줄이 남는다(확인 액션이 `revalidatePath("/")` 로
    // 충분한 것은 그쪽이 되살리려는 것이 목록 화면이기 때문이다).
    //
    // 🔵 **누른 그 자리에서 즉시 사라지지는 않는다** — 줄은 다음 렌더에서
    //    빠진다. 알고 받아들인 값이다(즉시 지우려면 목록 상태를 브라우저에
    //    들어야 하는데, 그러면 서버가 만든 목록과 두 벌이 된다).
    //
    // 🔵 포털의 30초 캐시에 걸리지 않는다 — 포털은 캐시에서 꺼낸 목록에도 지움을
    //    **그 자리에서** 다시 입힌다. 제 줄은 애초에 캐시를 거치지 않고 우리 DB
    //    에서 바로 온다.
    revalidatePath("/", "layout");
  } catch (error) {
    // 🔴 남기는 것은 오류의 **종류**뿐이다 — 열쇠에는 개선요청 id 가 들어 있다.
    console.error("dismissNotificationAction: failed", {
      name: error instanceof Error ? error.name : "unknown",
    });
  }
}

/**
 * ============================================================================
 * 「**보이는 알림 지우기 n건**」 — 지금 그려져 있는 줄을 한꺼번에 지운다
 * ============================================================================
 * 🔵 바로 위 dismissNotificationAction 과 **같은 약속 위에 있다.** 서버 액션인
 *    것도, 사람 번호를 제 세션에서 읽는 것도(브라우저가 보낸 값을 안 쓴다),
 *    권한을 따로 보지 않는 것도, 던지지 않는 것도, 열쇠를 로그에 안 찍는 것도,
 *    되살리는 자리가 사내 구간 **레이아웃**인 것도 같다 — 까닭은 전부 위
 *    머리말에 적혀 있고 여기서 되풀이하지 않는다. **다른 점 셋**만 적는다.
 *
 * ── 🔴 ① 받는 것이 **줄이 아니라 열쇠 목록**이다 ───────────────────────
 * @dss/ui 가 내준 자리는 `onDismissAll?: () => void` 로 **인자를 안 받는다.**
 * 그런데 「무엇이 전부인가」를 아는 것은 사이트다 — 종에 무엇을 그릴지 사이트가
 * 정하기 때문이다(그쪽 README 「보이는 알림 지우기」). 그래서 목록을 모아 이
 * 액션에 실어 보내는 일을 **종의 클라이언트 껍데기**가 한다
 * (components/NotificationBellWithAcknowledge.tsx 의 dismissVisibleNotifications —
 * 왜 거기서 모으는지도 그 자리에 적혀 있다).
 *
 * 🔴 넘어오는 값은 **`item.key`** 다. `item.id` 가 아니다 — 포털의 열쇠는
 *    `{client_id}:{id}` 이고, `id` 는 **우리 DB 의 확인 기록**이 쓰는 값이다
 *    (domain 의 bellKeyOf). 섞으면 포털이 조용히 버리거나, 더 나쁘게 확인 기록과
 *    모양이 얽힌다.
 *
 * ── 🔴 ② 그래서 받은 값을 **믿지 않는다** ───────────────────────────────
 * 열쇠가 브라우저를 한 번 거친다는 뜻이다. 🔵 새 위험은 아니다 — 줄마다 서는 ✕
 * 도 이미 브라우저가 보낸 `item.key` 를 쓴다. **누구의 지움인지(`sub`)는 여기서도
 * 서버가 제 세션에서 읽으므로**, 열쇠로 할 수 있는 일은 「내 종에서 이 줄을 그만
 * 보기」뿐이다. 다른 점은 **개수를 브라우저가 정한다**는 것 하나이고, 모양과 수를
 * 가리는 자리가 `vetDismissKeys` 다(domain/notifications.ts — 울타리 값의 근거도
 * 거기 적혀 있다). 배열이 아니면·울타리를 넘으면 **아무 일도 하지 않는다.**
 *
 * ── 🔴 ③ 거절당해도 되살린다 — 위와 **반대**다 ──────────────────────────
 * 위 함수는 「적히지 않았으면 되살리지 않는다」가 맞다. 한 줄짜리라 거절은 곧
 * 「아무것도 안 바뀌었다」이고, 그때 되살리면 캐시만 버린다.
 *
 * 여기서는 그 셈이 뒤집힌다. 열쇠가 200개를 넘으면 포털로 **여러 묶음**이 나가고
 * (oidc.ts 의 DISMISSALS_PER_REQUEST), 돌아오는 값은 「**전부** 적혔는가」다 —
 * 가운데 하나가 거절돼도 나머지는 적혔다. 그때 안 되살리면 **이미 지워진 줄이
 * 종에 그대로 남아** 사람은 「눌렀는데 아무 일도 없다」고 읽고, 다음 화면 이동까지
 * 어긋난 목록을 본다. 한 묶음이 통째로 거절된 때만 쓸데없이 캐시를 버리는데,
 * 그것은 사람이 단추를 **방금 누른** 직후라 다시 그리는 것이 손해가 아니다
 * (한 번 누름에 한 번뿐이다).
 * ============================================================================
 */
export async function dismissAllNotificationsAction(keys: readonly string[]): Promise<void> {
  try {
    const actor = await getSessionUser();
    if (!actor) return;

    // 🔴 타입이 `readonly string[]` 라고 해서 그 모양으로 오지 않는다 — 서버
    //    액션의 인자는 tsc 가 지키는 범위 밖이다(위 ②).
    const wanted = vetDismissKeys(keys);
    if (wanted === null) return;
    if (wanted.length === 0) return;

    // 🔴 돌려받는 「전부 적혔는가」를 **보지 않는다.** 일부만 적힌 경우가 있고,
    //    그때 되살리지 않으면 지워진 줄이 종에 남는다(위 ③).
    await dismissPortalNotifications(actor.authSub, wanted);
    revalidatePath("/", "layout");
  } catch (error) {
    // 🔴 여기도 오류의 **종류**뿐이다 — 몇 건이었는지도 적지 않는다.
    console.error("dismissAllNotificationsAction: failed", {
      name: error instanceof Error ? error.name : "unknown",
    });
  }
}
