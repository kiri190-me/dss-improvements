import type { ReactNode } from "react";

import { logoutAction } from "@/app/actions/auth";
import type { WebUser } from "@/lib/db/schema";

/**
 * 머리말.
 *
 * 서버 컴포넌트다 — "use client" 를 붙이지 않는다. 로그아웃은 서버 액션을
 * 부르는 평범한 <form> 이라 자바스크립트 없이도 동작한다. 사내망에서
 * 스크립트가 늦게 붙는 동안 눌러도 제대로 나가진다.
 *
 * 「통합 로그인으로」 버튼은 포털 앱 런처로 간다. 로그아웃과 다르다 —
 * 세션을 끊지 않으므로 돌아오면 그대로 들어와 있다.
 *
 * ── 🔴 이 한 줄에 무엇이 들어가나 (2026-09-18) ───────────────────────────
 * 한때 사내 시스템 오가기 메뉴바는 이 머리말 **위**에 회색 띠로 따로 앉아
 * 있었다. 화면 맨 위가 두 층이 되어 답답하고 본문이 한 줄만큼 줄어든다는
 * 사용자 지적으로 그 띠를 이 줄 **안**으로 들였다(@dss/ui README 3절의
 * variant="inline"). 그래서 이 줄은 이제 넷을 담는다:
 *
 *   시스템 이름 · 오가기 메뉴바 · 사용자명(+관리자) · 나가는 단추 둘
 *
 * 🔴 폰(360px)에서 그 넷이 다 들어가지 않는다. 실제 폭(글자 14px, 한글은
 * 한 자가 1em):
 *
 *   바깥 여백 px-4 를 뺀 속폭                                    328px
 *   ─────────────────────────────────────────────────────────────────
 *   시스템 이름 "DSS 개선요청" (16px)                          ~101px
 *   사용자명 3글자 + 「관리자」 뱃지                             ~96px
 *   「통합 로그인으로」  글자 102 + px-3 24 + 테두리 2          ~128px
 *   「로그아웃」          글자  56 + px-3 24 + 테두리 2          ~82px
 *   사이 여백 gap-4 + gap-3 두 번                                 40px
 *   ─────────────────────────────────────────────────────────────────
 *   합                                                          ~447px
 *
 * 메뉴바를 넣기 **전에 이미** 119px 넘친다 — 지금은 단추 글자가 두 줄로
 * 접혀 머리말이 두꺼워지는 것으로 버티고 있을 뿐이다. 여기에 메뉴바를 그냥
 * 끼우면 남는 자리가 0 이라 **폰에서 메뉴가 아예 보이지 않는다.**
 *
 * 그래서 폰에서는 **글자만 알려 주는 두 덩이**를 눈에서 감춘다 — 시스템
 * 이름과 사용자명이다. 둘 다 눌러서 갈 곳이 없는 정보고, 감추면 ~101 + 96 +
 * 여백 = ~213px 이 메뉴바 몫으로 돌아온다.
 *
 * ── 🔴 메뉴바가 드롭다운이 된 뒤에도 그 둘은 그대로 감춘다 (2026-09-18 오후)
 *
 * 메뉴바가 **단추 하나**가 되면서(@dss/ui) 폰에서 메뉴가 먹는 폭이
 * ~90px 에서 **59px** 로 줄었다. 그래서 감췄던 둘을 되돌릴 수 있는지 다시
 * 셈했는데, **되돌릴 수 없다**:
 *
 *   지금(둘 다 감춤)   단추 59 + gap 16 + 나가는 단추 둘 222      = 297 ≤ 328 ✔
 *   사용자명만 되돌림   96 + gap 12 가 더해져 오른쪽 묶음만 330   >  328 ✘
 *   이름까지 되돌림     101 + 16 + 59 + 16 + 222                  = 414 ✘
 *
 * 🔴 이 머리말에는 `flex-wrap` 이 없다(한 줄짜리 `justify-between` 이다).
 * 그래서 넘치면 줄이 바뀌는 것이 아니라 flex 가 칸을 min-content 까지 눌러
 * **단추 안에서 글자를 접는다** — "통합 / 로그인으로". 줄바꿈을 켜서 되돌리는
 * 길도 있지만 그것은 머리말이 **두 줄**이 된다는 뜻이라, 되돌려서 얻는 것보다
 * 잃는 것이 크다. 계측기(njlee)는 원래 `flex-wrap` 이고 폰에서 이미 두 줄이라
 * 그쪽은 이름을 되돌렸다 — 저장소마다 답이 다른 이유가 이것이다.
 *
 * 🔴 「통합 로그인으로」와 「로그아웃」은 감추지 않는다 — 그 둘 말고 이
 * 사이트를 떠날 길이 없다. 폰에서 가장 넓은 자리를 먹는 것이 그 둘이지만,
 * 나가는 길을 화면 밖으로 밀어내서는 안 된다.
 *
 * 🔴 감추는 방식은 `sr-only` 이지 `hidden` 이 **아니다** — 마크업에 그대로
 * 남아 화면 낭독기는 여전히 "DSS 개선요청" 과 사용자명을 읽는다. 게다가
 * sr-only 는 position:absolute 라 flex 항목에서 통째로 빠진다 — 폭뿐 아니라
 * 앞뒤 여백까지 함께 메뉴바로 간다.
 *
 * 🔴 감춰도 어디인지 알 수 있다: 본문 맨 위에 화면 이름이
 * <h1 class="text-2xl"> 로 크게 있고(ImprovementRequestsScreen), 메뉴 단추에는
 * 「지금 여기」인 서비스의 아이콘이 서 있고, 펼친 목록에서 그 칸은 폰에서도
 * 이름 + 2px 밑줄로 표시된다.
 *
 * 🔴 기준점은 `md:`(=768px) 하나다 — @dss/ui 가 **단추**에서 이름을 감추는
 * 기준과 같은 값이라야 그 사이 폭에서 「이름은 없는데 단추는 글자」인 어정쩡한
 * 상태가 생기지 않는다(service-menu.css 의 `not all and (min-width: 768px)`).
 *
 * 🔴 펼친 목록은 단추 아래로 **떠서**(position: absolute, z-index 50) 그려져
 * 이 머리말 밖으로 나온다. 그래서 이 <header> 와 그 조상(= (app)/layout.tsx 의
 * div, body, html)에 `overflow: hidden` 을 걸면 **목록이 잘려 아무것도 고를 수
 * 없게 된다.** 지금은 한 곳도 없고, 쌓임 맥락을 새로 만드는 것(z-index·
 * transform·filter·isolation)도 없다 — 그대로 두어야 한다.
 *
 * ── 🔴 다섯째 것 — 알림 종 (2026-09-21) ─────────────────────────────────
 * 이 줄에 @dss/ui 의 알림 종이 하나 더 붙었다. 다른 시스템들의 알림을 포털이
 * 합쳐 주고, 이 머리말이 그것을 그린다. 자리는 **줄의 맨 오른쪽 끝**이다.
 *
 * 🔴 맨 끝인 데는 까닭이 있다. 종의 펼친 목록은 종에 **오른쪽 끝을 맞춰**
 * 왼쪽으로 펼쳐지고(그쪽 CSS 의 `right: 0`), 폭이 `min(20rem, 100vw - 2rem)`
 * 이다. 폰(360px)에서 그 폭은 320px 이라, 종이 줄 가운데쯤(예: 사용자명 앞)에
 * 앉으면 목록의 왼쪽이 **화면 밖으로 나가 잘린다.** 종이 맨 끝에 있어야 목록
 * 오른쪽 끝이 머리말 오른쪽 여백에 맞고 320px 이 화면 안에 그대로 들어온다.
 * (A/S 도 같은 이유로 종이 머리말 맨 오른쪽이다.)
 *
 * 🔴 폰(360px)의 폭 셈은 이렇게 바뀐다 — 종은 40px 이다(@dss/ui 는 손가락
 * 화면에서 36 → 40 으로 키운다):
 *
 *   알림이 없을 때   종이 **아예 안 그려진다** → 297 ≤ 328 ✔ (예전 그대로)
 *   알림이 있을 때   297 + gap-3 12 + 종 40                   = 349 ✘ 21px 넘침
 *
 * 넘치면 이 줄은 flex-wrap 이 없어 「통합 / 로그인으로」처럼 단추 안에서 글자가
 * 접힌다 — 머리말이 두꺼워질 뿐 **없어지거나 못 누르게 되는 것은 없다.** 그
 * 21px 을 되찾으려면 나가는 단추(둘뿐인 나가는 길)를 줄이거나 여백을 손봐야
 * 하는데, 둘 다 「알림이 있는 폰」에서만 생기는 문제를 위해 **늘 있는** 것을
 * 건드리는 맞바꿈이라 하지 않았다. 종 자체는 40px 을 지키고(손가락 권고 44px에
 * 가깝다) 목록은 화면 안에 들어온다.
 */
export function AppHeader({
  user,
  portalUrl,
  serviceMenu = null,
  notificationBell = null,
}: {
  user: WebUser;
  portalUrl: string;
  /**
   * 사내 시스템 오가기 목록(@dss/ui 의 ServiceMenuBar). (app)/layout.tsx 가
   * 서버에서 만들어 내려보내고, 이 머리말이 **이름과 사용자명 사이**에 그린다.
   *
   * 조각이 아니라 **다 그려진 노드**를 받는 이유: 이 파일이 @dss/ui 도, 목록을
   * 어디서 구하는지도 몰라야 한다. 그리는 자리만 여기가 정한다(아래
   * `shrink-0 mr-auto` 한 겹 — 그것이 이 줄의 선을 지키는 장치다).
   * 목록이 비면 그 조각이 스스로 null 이라 빈 칸만 남고 아무것도 안 보인다.
   */
  serviceMenu?: ReactNode;
  /**
   * 알림 종(@dss/ui 의 NotificationBell). 메뉴바와 **같은 방식**으로 받는다 —
   * 다 그려진 노드다. 이 파일은 @dss/ui 도, 알림을 어디서 구하는지도 모른다.
   *
   * (app)/layout.tsx 가 `<Suspense>` 로 감싼 조각을 내려보내므로, 포털이
   * 느려도 이 머리말은 기다리지 않는다 — 종만 나중에 흘러 들어온다.
   *
   * 🔴 그릴 알림이 없으면 그 조각이 **스스로 null** 이다(@dss/ui 의 판단 —
   * 눌러도 아무것도 없는 단추를 머리말에 남기지 않는다). 그래서 래퍼 <div> 로
   * 감싸지 않고 **flex 항목으로 그대로** 둔다: 감싸면 알림이 없을 때도 빈
   * 항목과 그 앞 여백(gap-3 12px)이 남아 머리말이 예전과 달라진다.
   */
  notificationBell?: ReactNode;
}) {
  return (
    <header className="border-b border-slate-200 bg-white">
      <div className="mx-auto flex w-full max-w-[1100px] items-center justify-between gap-4 px-4 py-3">
        {/*
          시스템 이름. 폰(<768px)에서는 **눈에서만** 감춘다 — 왜인지는 이 파일
          머리말의 폭 계산에 있다. 낭독기에는 그대로 남고, 본문 맨 위에는 화면
          이름이 큰 글씨로 따로 있다.
        */}
        <h1 className="sr-only text-base font-semibold text-slate-900 md:not-sr-only">
          DSS 개선요청
        </h1>

        {/*
          사내 시스템 오가기 목록. 이름 다음, 사용자명 앞 — 넓은 화면에서
          통째로 비어 있던 가운데 자리다.

          🔴 `shrink-0 mr-auto` 다(2026-09-18 오후, `min-w-0 flex-1` 에서 바꿨다).

          왜 바꿨나. 예전 것은 「**가로로 늘어선 목록**에 남는 자리를 준다」는
          장치였다 — 기준 폭 0 으로 두고 넘치면 목록이 제 안에서 굴러가게
          (`.dss-menu__list { overflow-x: auto }`) 하는 짝이었다. 이제 그리는
          것은 **단추 하나**이고, 그 단추는 `white-space: nowrap` 이라 줄어들지
          못한다 — 기준 폭 0 인 칸에 넣어 두면 자리가 모자랄 때 단추가 제 칸
          밖으로 삐져나와 사용자명·나가는 단추와 겹친다.

          `shrink-0` 은 기준 폭을 **제 내용 폭**으로 둔다 — 폰 59px(아이콘만),
          768px 이상 113px(아이콘 + "개선요청"). 서비스가 다섯이 되어도 그대로다.

          🔴 `mr-auto` 가 짝이다. 이 줄은 `justify-between` 인데, 항목이 셋이고
          가운데 것이 남는 자리를 먹지 않게 되면 justify-between 이 그 단추를
          **줄 한가운데로 밀어 버린다.** 자동 여백은 justify-content 보다 먼저
          남는 자리를 가져가므로, `mr-auto` 한 낱말이 단추를 이름 바로 옆에
          붙들어 둔다 — `flex-1` 일 때와 그려지는 자리가 같다.
        */}
        <div className="shrink-0 mr-auto">{serviceMenu}</div>

        <div className="flex items-center gap-3 text-sm">
          {/*
            누구로 들어와 있는지. 폰에서는 **눈에서만** 감춘다(위와 같은 이유) —
            눌러서 갈 곳이 없는 정보라 좁은 화면에서 가장 먼저 내줄 자리다.
            낭독기는 그대로 읽으므로 「내가 누구로 들어와 있나」를 확인할 길은
            남는다.
          */}
          <span className="sr-only text-slate-600 md:not-sr-only">
            {user.displayName}
            {user.role === "ADMIN" && (
              <span className="ml-1.5 rounded bg-slate-100 px-1.5 py-0.5 text-xs text-slate-500">
                관리자
              </span>
            )}
          </span>

          {/* 🔴 아래 둘은 폰에서도 감추지 않는다 — 이 사이트를 떠나는 유일한 길이다. */}
          <a
            href={portalUrl}
            className="rounded-md border border-slate-300 px-3 py-1.5 text-slate-700 hover:bg-slate-50"
          >
            통합 로그인으로
          </a>

          <form action={logoutAction}>
            <button
              type="submit"
              className="rounded-md border border-slate-300 px-3 py-1.5 text-slate-700 hover:bg-slate-50"
            >
              로그아웃
            </button>
          </form>

          {/*
            알림 종. 🔴 **줄의 맨 오른쪽 끝**이다 — 펼친 목록이 종에 오른쪽
            끝을 맞춰 왼쪽으로 펼쳐지므로(그쪽 CSS 의 right: 0), 가운데쯤에
            앉으면 폰에서 목록 왼쪽이 화면 밖으로 잘린다. 자세한 셈은 이 파일
            머리말의 「다섯째 것」 절에 있다.

            래퍼 <div> 로 감싸지 않는다: 알림이 없으면 조각이 스스로 null 이라
            항목 자체가 사라져야 하는데, 감싸면 빈 항목과 그 앞 여백이 남는다.
          */}
          {notificationBell}
        </div>
      </div>
    </header>
  );
}
